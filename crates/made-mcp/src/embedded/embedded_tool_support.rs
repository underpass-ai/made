//! Which tools the embedded engine serves.
//!
//! One predicate, asked by the backend's `supports_tool` and by the
//! terminal `grant` command when it maps a tool profile to the actions
//! a person is about to allow. Its own file so the backend's dispatch
//! table and this list, which must agree, are each read whole.

use super::embedded_extension_dispatch;
use crate::mcp_protocol::{
    ACCEPT_CHILD_COMPLETION_TOOL, ADOPT_EXECUTION_RECEIPT_TOOL, APPLY_PROTOCOL_TRANSITION_TOOL,
    APPROVE_PROTOCOL_GUARD_TOOL, ASSERT_PROTOCOL_REASON_TOOL, BIND_PROTOCOL_PARTICIPANTS_TOOL,
    CANCEL_PROTOCOL_TOOL, CLAIM_PROTOCOL_STEP_TOOL, CLOSE_PROTOCOL_INTERVENTION_TOOL,
    COLLECT_PROTOCOL_EVIDENCE_TOOL, COMPLETE_EXECUTION_RECEIPT_TOOL, COMPLETE_PROTOCOL_STEP_TOOL,
    DEFER_PROTOCOL_GUARD_TOOL, DESIGN_PROTOCOL_TOOL, DIFF_PROTOCOL_DEFINITIONS_TOOL,
    ENFORCE_PROTOCOL_DEADLINES_TOOL, EXPLAIN_PROTOCOL_DRAFT_TOOL, GENERATE_PROTOCOL_REPORT_TOOL,
    GET_EXECUTION_RECEIPT_TOOL, GET_METRICS_TOOL, GET_PROTOCOL_INSTANCE_TOOL,
    GET_PROTOCOL_TRANSCRIPT_TOOL, GET_STATUS_TOOL, INSPECT_EXECUTION_RECOVERY_TOOL,
    INSPECT_PROTOCOL_RESUME_TOOL, LIST_PROTOCOL_INSTANCES_TOOL, PAUSE_PROTOCOL_TOOL,
    PREPARE_PROTOCOL_CHILDREN_TOOL, PUBLISH_PROTOCOL_DEFINITION_TOOL, PULL_PROTOCOL_EVENTS_TOOL,
    READ_PROTOCOL_EVENTS_TOOL, RECORD_PROTOCOL_HOST_HANDOFF_TOOL, RECOVER_PROTOCOL_CHILDREN_TOOL,
    RENEW_PROTOCOL_STEP_LEASE_TOOL, REQUEST_PROTOCOL_INTERVENTION_TOOL,
    RESPOND_TO_PROTOCOL_INTERVENTION_TOOL, RESUME_PROTOCOL_TOOL, RUN_PROTOCOL_STEP_TOOL,
    RUN_PROTOCOL_TOOL, SEARCH_PROTOCOL_INSTANCES_TOOL, START_PROTOCOL_TOOL,
    START_PUBLISHED_PROTOCOL_TOOL, STREAM_PROTOCOL_TOOL, VALIDATE_PROTOCOL_DRAFT_TOOL,
    VERIFY_PROTOCOL_JOURNAL_TOOL,
};

/// Whether the embedded engine serves `name`: every tool of the
/// catalog this backend has an arm for. A function rather than only a
/// method so that a command with no backend in hand (the terminal
/// `grant`, mapping a tool profile to actions) asks the same question.
#[must_use]
pub(crate) fn embedded_supports_tool(name: &str) -> bool {
    if embedded_extension_dispatch::handles(name) {
        return true;
    }
    matches!(
        name,
        RUN_PROTOCOL_TOOL
            | START_PROTOCOL_TOOL
            | RUN_PROTOCOL_STEP_TOOL
            | PREPARE_PROTOCOL_CHILDREN_TOOL
            | ACCEPT_CHILD_COMPLETION_TOOL
            | RECOVER_PROTOCOL_CHILDREN_TOOL
            | CLAIM_PROTOCOL_STEP_TOOL
            | RENEW_PROTOCOL_STEP_LEASE_TOOL
            | COMPLETE_PROTOCOL_STEP_TOOL
            | GET_EXECUTION_RECEIPT_TOOL
            | INSPECT_EXECUTION_RECOVERY_TOOL
            | COMPLETE_EXECUTION_RECEIPT_TOOL
            | ADOPT_EXECUTION_RECEIPT_TOOL
            | APPROVE_PROTOCOL_GUARD_TOOL
            | DEFER_PROTOCOL_GUARD_TOOL
            | APPLY_PROTOCOL_TRANSITION_TOOL
            | PAUSE_PROTOCOL_TOOL
            | RESUME_PROTOCOL_TOOL
            | RECORD_PROTOCOL_HOST_HANDOFF_TOOL
            | INSPECT_PROTOCOL_RESUME_TOOL
            | CANCEL_PROTOCOL_TOOL
            | ENFORCE_PROTOCOL_DEADLINES_TOOL
            | GET_PROTOCOL_INSTANCE_TOOL
            | LIST_PROTOCOL_INSTANCES_TOOL
            | SEARCH_PROTOCOL_INSTANCES_TOOL
            | REQUEST_PROTOCOL_INTERVENTION_TOOL
            | RESPOND_TO_PROTOCOL_INTERVENTION_TOOL
            | CLOSE_PROTOCOL_INTERVENTION_TOOL
            | COLLECT_PROTOCOL_EVIDENCE_TOOL
            | ASSERT_PROTOCOL_REASON_TOOL
            | DESIGN_PROTOCOL_TOOL
            | VALIDATE_PROTOCOL_DRAFT_TOOL
            | EXPLAIN_PROTOCOL_DRAFT_TOOL
            | PUBLISH_PROTOCOL_DEFINITION_TOOL
            | START_PUBLISHED_PROTOCOL_TOOL
            | DIFF_PROTOCOL_DEFINITIONS_TOOL
            | BIND_PROTOCOL_PARTICIPANTS_TOOL
            | READ_PROTOCOL_EVENTS_TOOL
            | STREAM_PROTOCOL_TOOL
            | PULL_PROTOCOL_EVENTS_TOOL
            | VERIFY_PROTOCOL_JOURNAL_TOOL
            | GET_PROTOCOL_TRANSCRIPT_TOOL
            | GENERATE_PROTOCOL_REPORT_TOOL
            | GET_STATUS_TOOL
            | GET_METRICS_TOOL
    )
}
